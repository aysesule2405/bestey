/** Build a link for the given language. Paths are written without the /tr prefix. */
export const href = (lang: Lang, path = '/') => (lang === 'tr' ? `/tr${path === '/' ? '/' : path}` : path);

export const formatDate = (date: string, lang: Lang) => {
  const [y, m] = date.split('-');
  if (!m) return y;
  const month = new Date(Number(y), Number(m) - 1, 1).toLocaleString(lang === 'tr' ? 'tr-TR' : 'en-US', { month: 'long' });
  return `${lang === 'tr' ? month : month.toLowerCase()} ${y}`.toLowerCase();
};
